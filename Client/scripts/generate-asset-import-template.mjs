import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import XLSX from '@e965/xlsx'

const __dirname = dirname(fileURLToPath(import.meta.url))

/** Minimal columns; any extra headers you add are stored in `custom_fields` on each asset. */
const headers = [
  'category_slug',
  'category_name',
  'serial_number',
  'manufacturer_name',
  'model',
  'location_code',
  'location_name',
  'purchase_date',
  'warranty_expiry',
  'status',
  'notes',
]

const wb = XLSX.utils.book_new()
const importData = [headers]
const ws = XLSX.utils.aoa_to_sheet(importData)
XLSX.utils.book_append_sheet(wb, ws, 'Import')

const readme = [
  ['Asset bulk import'],
  [''],
  ['Use the Import sheet. Row 1 = headers; add data from row 2 onward.'],
  ['Required per row: category_slug OR category_name, and serial_number.'],
  ['If both category columns are blank, the category selected on the Add new asset page is used (when set).'],
  ['Asset tags are generated by the system — do not add an asset_tag column.'],
  [''],
  ['Optional: manufacturer_name, model, locations, dates (yyyy-mm-dd), status, notes.'],
  ['Any extra columns you add (e.g. ram_type, wifi_mac, custom_band) are saved under custom_fields on the asset.'],
  ['Use custom_* column names if you prefer keys like custom_vendor → stored as vendor.'],
  ['Short headers like Type or Vendor are not remapped to category/manufacturer — use category_slug / manufacturer_name.'],
  [''],
  ['Rejected: duplicate serial_number within the same file; assignment / employee columns.'],
  ['App template_version: 5'],
]
const wsR = XLSX.utils.aoa_to_sheet(readme)
XLSX.utils.book_append_sheet(wb, wsR, 'Readme')

const out = join(__dirname, '..', 'public', 'asset-import-template.xlsx')
writeFileSync(out, XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }))
